import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { checkStaleness } from "../src/checkStale.mjs";
import { generateMap } from "../src/generateMap.mjs";

const CLI = fileURLToPath(new URL("../bin/claude-mapper.mjs", import.meta.url));

function withTempDir(fn) {
  const tmp = mkdtempSync(join(tmpdir(), "claude-mapper-check-test-"));
  try { fn(tmp); } finally { rmSync(tmp, { recursive: true, force: true }); }
}
function feature(root, name) {
  mkdirSync(join(root, "src", "features", name), { recursive: true });
}
function runCheck(root, ...args) {
  return spawnSync(process.execPath, [CLI, "check", ...args], { cwd: root, encoding: "utf8" });
}

test("check reports a freshly generated map as current, even without Git", () => withTempDir((root) => {
  feature(root, "auth");
  generateMap(root);
  assert.deepEqual(checkStaleness(root), { staleCount: 0, results: [] });
  assert.equal(runCheck(root).status, 0);
}));

test("check detects a new folder without a Git commit and prints changed rows", () => withTempDir((root) => {
  feature(root, "auth");
  generateMap(root);
  const before = readFileSync(join(root, "MAP.md"), "utf8");
  feature(root, "billing");
  const result = checkStaleness(root);
  assert.equal(result.staleCount, 1);
  assert.equal(result.results[0].reason, "content-changed");
  assert.match(result.results[0].changes.join("\n"), /Features.*\(2\).*auth.*billing/);
  const cli = runCheck(root);
  assert.equal(cli.status, 1);
  assert.match(cli.stdout, /\+ .*Features.*\(2\)/);
  assert.equal(readFileSync(join(root, "MAP.md"), "utf8"), before, "check must not modify the file");
}));

test("check detects a deleted feature directory", () => withTempDir((root) => {
  feature(root, "auth"); feature(root, "billing");
  generateMap(root);
  rmSync(join(root, "src", "features", "billing"), { recursive: true, force: true });
  const result = checkStaleness(root);
  assert.equal(result.staleCount, 1);
  assert.match(result.results[0].changes.join("\n"), /Features.*\(1\)/);
}));

test("check ignores manual notes outside the AUTO section", () => withTempDir((root) => {
  feature(root, "auth");
  generateMap(root);
  const path = join(root, "MAP.md");
  writeFileSync(path, readFileSync(path, "utf8") + "\nMy private notes, edited today.\n");
  assert.equal(checkStaleness(root).staleCount, 0);
}));

test("check flags missing MAP.md with nonzero CLI status", () => withTempDir((root) => {
  feature(root, "auth");
  const result = checkStaleness(root);
  assert.equal(result.staleCount, 1);
  assert.equal(result.results[0].reason, "missing");
  assert.equal(runCheck(root).status, 1);
  assert.match(runCheck(root).stdout, /MAP\.md is missing/);
}));

test("check flags missing or broken AUTO markers", () => withTempDir((root) => {
  feature(root, "auth"); generateMap(root);
  const path = join(root, "MAP.md");
  writeFileSync(path, readFileSync(path, "utf8").replace("<!-- AUTO:END -->", "<!-- BROKEN -->"));
  assert.equal(checkStaleness(root).results[0].reason, "invalid-markers");
  assert.equal(runCheck(root).status, 1);
}));

test("check --all checks only recognized repos and honors --match", () => withTempDir((root) => {
  for (const name of ["app-one", "app-two"]) {
    const dir = join(root, name);
    mkdirSync(dir);
    writeFileSync(join(dir, "package.json"), "{}");
    feature(dir, "auth");
    generateMap(dir);
  }
  mkdirSync(join(root, "ordinary-folder"));
  feature(join(root, "app-two"), "billing");
  const result = checkStaleness(root, { multiRepo: true });
  assert.equal(result.staleCount, 1);
  assert.equal(result.results[0].repo, "app-two");
  assert.equal(runCheck(root, "--all").status, 1);
  assert.equal(runCheck(root, "--all", "--match", "^app-one$").status, 0);
}));

test("check --all reports a missing map in a recognized repository", () => withTempDir((root) => {
  const repo = join(root, "app-one");
  mkdirSync(repo);
  writeFileSync(join(repo, "package.json"), "{}");
  assert.equal(checkStaleness(root, { multiRepo: true }).results[0].reason, "missing");
}));

test("check shows differences in other AUTO lines", () => withTempDir((root) => {
  feature(root, "auth");
  generateMap(root);

  const mapPath = join(root, "MAP.md");
  const original = readFileSync(mapPath, "utf8");

  const modified = original.replace(
    "Generated by `claude-mapper`",
    "Generated by `another-tool`"
  );

  assert.notEqual(modified, original);
  writeFileSync(mapPath, modified);

  const result = checkStaleness(root);

  assert.equal(result.staleCount, 1);
  assert.ok(
    result.results[0].changes.some((line) => line.includes("another-tool")),
    "Expected the changed AUTO line to appear in the differences"
  );
}));

test("check displays a removed duplicate AUTO line", () => withTempDir((root) => {
  feature(root, "auth");
  generateMap(root);

  const mapPath = join(root, "MAP.md");
  const original = readFileSync(mapPath, "utf8");
  const featureLine = original.split(/\r?\n/).find((line) => line.includes("- **Features**"));

  assert.ok(featureLine);

  writeFileSync(mapPath, original.replace(featureLine, `${featureLine}\n${featureLine}`));

  const result = checkStaleness(root);

  assert.equal(result.staleCount, 1);
  assert.ok(
    result.results[0].changes.some((line) => line.startsWith("- ") && line.includes("Features"))
  );
}));

test("check displays differences when AUTO lines are reordered", () => withTempDir((root) => {
  feature(root, "auth");
  mkdirSync(join(root, "src", "routes"), { recursive: true });
  writeFileSync(join(root, "src", "routes", "usersRoute.ts"), "");

  generateMap(root);

  const mapPath = join(root, "MAP.md");
  const lines = readFileSync(mapPath, "utf8").split(/\r?\n/);

  const featureIndex = lines.findIndex((line) => line.startsWith("- **Features**"));
  const routeIndex = lines.findIndex((line) => line.startsWith("- **Routes**"));

  assert.ok(featureIndex >= 0);
  assert.ok(routeIndex >= 0);

  [lines[featureIndex], lines[routeIndex]] = [lines[routeIndex], lines[featureIndex]];
  writeFileSync(mapPath, lines.join("\n"));

  const result = checkStaleness(root);

  assert.equal(result.staleCount, 1);
  assert.equal(result.results[0].reason, "content-changed");
  assert.ok(result.results[0].changes.some((line) => line.startsWith("- ")));
  assert.ok(result.results[0].changes.some((line) => line.startsWith("+ ")));
}));
